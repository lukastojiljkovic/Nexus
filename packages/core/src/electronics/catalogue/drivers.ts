/**
 * The parts that stand between a board pin and something it cannot drive.
 *
 * A driver exists because a GPIO pin gives 20 mA at the board's logic level and
 * the load wants amps, or a different voltage, or more pins than the board has.
 * That is why this group is where the pin-expander and level-shifter entries
 * live alongside the motor drivers: they solve the same problem in a different
 * dimension.
 *
 * None of them is `kind: "power"`, even though several take a motor supply —
 * `power` is reserved for parts whose JOB is to produce a rail, and the
 * validator's `board` rule uses that distinction: only a board or a `power` part
 * may have a `power-out` pin. The L298N is where that boundary bites: its
 * on-board regulator really does put out 5 V, but the part is a motor driver, so
 * it stays here and that pin is left off the entry rather than turned into a
 * rail the current budget would then treat as a supply. Anyone powering a board
 * from it is doing something the catalogue declines to bless.
 */

